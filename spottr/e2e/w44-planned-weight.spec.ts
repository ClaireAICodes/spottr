import { test, expect } from '@playwright/test'

for (const width of [320, 390]) {
  test(`empty planned weight stays a draft; explicit zero survives start edit and offline Resume at ${width}`, async ({ page, context }, testInfo) => {
    await page.setViewportSize({ width, height: 667 })
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('/spottr/#/gyms')
    await page.getByRole('button', { name: 'Add gym', exact: true }).click()
    await page.getByLabel('Gym name').fill('Weight gym')
    await page.getByRole('button', { name: 'Save gym', exact: true }).click()
    await expect(page.getByRole('article', { name: 'Weight gym', exact: true })).toBeVisible()
    await page.getByRole('tab', { name: 'Workouts', exact: true }).click()
    await page.getByRole('button', { name: 'Add workout', exact: true }).click()
    await page.getByLabel('Workout name', { exact: true }).fill('Explicit zero')
    await page.getByRole('button', { name: 'Create new exercise', exact: true }).click()
    await page.getByLabel('Exercise name', { exact: true }).fill('Press')
    await page.getByRole('button', { name: 'Save exercise', exact: true }).click()
    const weight = page.getByLabel('Set 1 weight (kg) — Press, exercise 1', { exact: true })
    await weight.fill('')
    await page.getByRole('button', { name: 'Save workout', exact: true }).click()
    await expect(page.getByRole('alert')).toHaveText('Enter a weight of zero or more.')
    await expect(weight).toBeFocused()
    await expect(weight).toHaveValue('')
    await expect(page.getByRole('button', { name: 'Edit Explicit zero', exact: true })).toHaveCount(0)
    await page.screenshot({ path: testInfo.outputPath(`empty-${width}.png`), fullPage: true })
    await page.getByRole('tab', { name: 'Exercises', exact: true }).click()
    await page.getByRole('tab', { name: 'Workouts', exact: true }).click()
    await expect(weight).toHaveValue('')
    await page.reload()
    await expect(weight).toHaveValue('')
    await weight.fill('0')
    await page.getByRole('button', { name: 'Save workout', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Edit Explicit zero', exact: true })).toBeFocused()
    await page.getByRole('tab', { name: 'Home', exact: true }).click()
    await page.getByRole('button', { name: 'Start workout at Weight gym', exact: true }).click()
    await page.getByRole('button', { name: 'Start Explicit zero', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Press', exact: true })).toBeVisible()
    await expect(page.getByRole('region', { name: 'Current set', exact: true })).toContainText('Planned: 0 kg × 8')
    // Exit retains the captured session while future routine edits stay separate.
    await page.getByRole('button', { name: /Exit/ }).click()
    await page.getByRole('tab', { name: 'Workouts', exact: true }).click()
    await page.getByRole('button', { name: 'Edit Explicit zero', exact: true }).click()
    await weight.fill('')
    await page.getByRole('button', { name: 'Save workout', exact: true }).click()
    await expect(page.getByRole('alert')).toHaveText('Enter a weight of zero or more.')
    await weight.fill('8')
    await page.getByRole('button', { name: 'Save workout', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Edit Explicit zero', exact: true })).toBeFocused()
    await page.getByRole('tab', { name: 'Home', exact: true }).click()
    await context.setOffline(true)
    await page.reload()
    await page.getByRole('button', { name: 'Resume Explicit zero', exact: true }).click()
    await expect(page.getByRole('region', { name: 'Current set', exact: true }).getByRole('spinbutton', { name: /weight/i })).toHaveValue('0')
    await page.screenshot({ path: testInfo.outputPath(`resume-${width}.png`), fullPage: true })
    expect(errors).toEqual([])
  })
}
