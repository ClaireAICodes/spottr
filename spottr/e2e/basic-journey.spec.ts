import { expect, test } from '@playwright/test'

for (const width of [390, 834, 1440]) {
  test(`canonical sections and connected skip-return workout at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 844 })
    await page.goto('./')
    await expect(page.getByRole('tab')).toHaveText(['Home', 'Exercises', 'Workouts', 'Gyms', 'Settings'])
    // Omission is an authorized alternative to an actual current date/profile feature.
    await expect(page.locator('.topbar .eyebrow')).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'Open profile' })).toHaveCount(0)
    await page.getByRole('button', { name: 'Manage gyms' }).click()
    await page.getByRole('button', { name: 'Add gym', exact: true }).click()
    await page.getByLabel('Gym name').fill('Journey Gym')
    await page.getByRole('button', { name: 'Save gym' }).click()
    await page.getByRole('button', { name: 'Back to home' }).click()
    await page.getByRole('tab', { name: 'Exercises', exact: true }).click()
    await expect(page.getByRole('tabpanel', { name: 'Exercises', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Add exercise', exact: true }).click()
    await page.getByLabel('Exercise name').fill('Journey Row')
    await page.getByRole('button', { name: 'Save exercise' }).click()
    await page.getByRole('tab', { name: 'Workouts', exact: true }).click()
    await expect(page.getByRole('tabpanel', { name: 'Workouts', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Add workout' }).click()
    await page.getByLabel('Workout name').fill('Journey Strength')
    await page.getByRole('button', { name: 'Add Journey Row' }).click()
    const sets = page.getByRole('article', { name: 'Journey Row sets' })
    await sets.getByLabel('Set 1 weight').fill('40')
    await sets.getByLabel('Set 1 reps').fill('5')
    await sets.getByRole('button', { name: 'Add set' }).click()
    await sets.getByLabel('Set 2 weight').fill('30')
    await sets.getByLabel('Set 2 reps').fill('6')
    await page.getByRole('button', { name: 'Save workout' }).click()
    await page.getByRole('tab', { name: 'Home', exact: true }).click()
    await page.getByRole('button', { name: 'Start workout at Journey Gym' }).click()
    await page.getByRole('button', { name: 'Start Journey Strength' }).click()
    await page.getByRole('button', { name: 'Log Journey Row set 1', exact: true }).click()
    await expect(page.getByText('1 of 2 sets logged · 0 skipped')).toBeVisible()
    await expect(page.getByRole('timer', { name: 'Rest timer' })).toBeVisible()
    await page.getByRole('button', { name: 'Stop rest', exact: true }).click()
    await page.getByRole('button', { name: 'Skip Journey Row set 2', exact: true }).click()
    await expect(page.getByLabel('Journey Row set 2 weight')).toBeDisabled()
    await expect(page.getByText('1 of 2 sets logged · 1 skipped')).toBeVisible()
    await page.reload()
    await page.getByRole('button', { name: 'Resume Journey Strength' }).click()
    await expect(page.getByText('1 of 2 sets logged · 1 skipped')).toBeVisible()
    await page.getByRole('button', { name: 'Return to Journey Row set 2', exact: true }).click()
    await expect(page.getByText('1 of 2 sets logged · 0 skipped')).toBeVisible()
    await expect(page.getByLabel('Journey Row set 2 weight')).toBeEnabled()
    await page.getByRole('button', { name: 'Log Journey Row set 2', exact: true }).click()
    await expect(page.getByText('2 of 2 sets logged · 0 skipped')).toBeVisible()
    await page.getByRole('button', { name: 'Stop rest', exact: true }).click()
    await page.getByRole('button', { name: 'Finish workout', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Workout saved' })).toBeVisible()
    await expect(page.getByText('380 kg', { exact: true })).toBeVisible()
    await expect(page.getByText('2 sets completed', { exact: true })).toBeVisible()
    await expect(page.getByText('0 sets skipped', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'View history', exact: true }).click()
    await page.reload()
    await page.getByRole('tab', { name: 'Workouts', exact: true }).click()
    await page.getByRole('button', { name: 'History', exact: true }).click()
    const history = page.getByRole('article', { name: 'Journey Strength at Journey Gym' })
    await expect(history).toContainText('380 kg')
    await history.getByRole('button', { name: 'View details' }).click()
    await expect(history).toContainText('40 kg × 5 reps')
    await expect(history).toContainText('30 kg × 6 reps')
    await expect(history.getByText('Completed', { exact: true })).toHaveCount(2)
    await page.screenshot({ path: `evidence/basic-journey-results/history-${width}.png`, fullPage: true })
  })
}
