import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('elapsed rest survives its suggestion, subsequent logging and reload until manually stopped', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.clock.install({ time: new Date('2026-10-01T10:00:00Z') })
  await page.goto('/')
  await page.getByRole('button', { name: 'Manage gyms' }).click()
  await page.getByRole('button', { name: 'Add gym', exact: true }).click()
  await page.getByLabel('Gym name').fill('Rest Gym')
  await page.getByRole('button', { name: 'Save gym' }).click()
  await page.getByRole('button', { name: 'Back to home' }).click()
  await page.getByRole('tab', { name: 'Train' }).click()
  await page.getByRole('button', { name: 'Add exercise', exact: true }).click()
  await page.getByLabel('Exercise name').fill('Row')
  await page.getByRole('button', { name: 'Save exercise' }).click()
  await page.getByRole('tab', { name: 'Plan' }).click()
  await page.getByRole('button', { name: 'Add workout' }).click()
  await page.getByLabel('Workout name').fill('Rest Recovery')
  await page.getByRole('button', { name: 'Add Row' }).click()
  await page.getByRole('button', { name: 'Add set' }).click()
  await page.getByRole('button', { name: 'Save workout' }).click()
  await page.getByRole('tab', { name: 'Settings' }).click()
  await page.getByLabel('Rest duration (seconds)').fill('15')
  await page.getByRole('button', { name: 'Save settings' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Settings saved' })).toBeVisible()
  await page.getByRole('tab', { name: 'Home' }).click()
  await page.getByRole('button', { name: 'Start workout at Rest Gym' }).click()
  await page.getByRole('button', { name: 'Start Rest Recovery' }).click()
  await page.clock.pauseAt(new Date('2026-10-01T10:01:00Z'))
  await page.getByRole('button', { name: 'Log Row set 1' }).click()
  const timer = page.getByRole('timer', { name: 'Rest timer' })
  await expect(timer).toHaveText('0:00')
  await page.clock.fastForward(20000)
  await expect(timer).toHaveText('0:20')
  await page.getByRole('button', { name: 'Log Row set 2' }).click()
  await expect(page.getByText('2 of 2 sets logged')).toBeVisible()
  await expect(timer).toHaveText('0:20')
  await page.getByRole('button', { name: 'Exit workout' }).click()
  await page.getByRole('tab', { name: 'Settings' }).click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download backup' }).click()
  const download = await downloadPromise
  const backup = JSON.parse(await readFile((await download.path())!, 'utf8'))
  expect(backup.version).toBe(1)
  expect(backup.entities.activeSession.restTimer).toEqual({
    startedAt: '2026-10-01T10:01:00.000Z', endsAt: '2026-10-01T10:01:15.000Z',
  })
  await page.clock.fastForward(45000)
  await page.reload()
  await page.getByRole('button', { name: 'Resume Rest Recovery' }).click()
  await expect(timer).toHaveText('1:05')
  await page.screenshot({ path: 'evidence/screenshots/elapsed-rest-390.png', fullPage: true })
  await page.getByRole('button', { name: 'Stop rest' }).focus()
  await page.keyboard.press('Enter')
  await expect(timer).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Finish workout' })).toBeFocused()
  await page.reload()
  await page.getByRole('button', { name: 'Resume Rest Recovery' }).click()
  await expect(timer).toHaveCount(0)
  // The unchanged v1 timer shape is also the pre-change countdown backup shape.
  await page.getByRole('button', { name: 'Exit workout' }).click()
  await page.getByRole('tab', { name: 'Settings' }).click()
  await page.getByLabel('Choose backup file').setInputFiles({
    name: 'legacy-v1-rest.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)),
  })
  await expect(page.getByRole('status').filter({ hasText: 'compatible and ready' })).toBeVisible()
  await page.getByRole('button', { name: 'Restore backup' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Backup restored' })).toBeVisible()
  await page.getByRole('tab', { name: 'Home' }).click()
  await page.getByRole('button', { name: 'Resume Rest Recovery' }).click()
  await expect(timer).toHaveText('1:05')
  await page.getByRole('button', { name: 'Stop rest' }).click()
  await page.getByRole('button', { name: 'Exit workout' }).click()
  await page.getByRole('tab', { name: 'Settings' }).click()
  await page.getByLabel('Rest reminders').uncheck()
  await page.getByRole('button', { name: 'Save settings' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Settings saved' })).toBeVisible()
  await page.getByRole('tab', { name: 'Home' }).click()
  await page.getByRole('button', { name: 'Resume Rest Recovery' }).click()
  await page.getByRole('button', { name: 'Finish workout' }).click()
  await page.getByRole('button', { name: 'Back to home' }).click()
  await page.getByRole('button', { name: 'Start workout at Rest Gym' }).click()
  await page.getByRole('button', { name: 'Start Rest Recovery' }).click()
  await page.getByRole('button', { name: 'Log Row set 1' }).click()
  await expect(page.getByText('1 of 2 sets logged')).toBeVisible()
  await expect(timer).toHaveCount(0)
})
