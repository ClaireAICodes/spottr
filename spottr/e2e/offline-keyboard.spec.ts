import { expect, test, type Locator } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import type { SpottrBackup } from '../src/backup'

for (const viewport of [{ width: 390, height: 844 }, { width: 390, height: 667 }, { width: 834, height: 844 }, { width: 1440, height: 844 }]) {
  test(`cached-ready keyboard core journey ${viewport.width}x${viewport.height}`, async ({ page, context }) => {
    await page.setViewportSize(viewport)
    await page.goto('/')
    await expect(page.locator('html')).toHaveAttribute('data-offline-ready', 'true')
    // Only gym fixture preparation is pointer-driven. All acceptance actions below
    // traverse the real document with Tab/arrows; no focus() or click() shortcuts.
    await page.getByRole('button', { name: 'Manage gyms' }).click()
    await page.getByRole('button', { name: 'Add gym', exact: true }).click()
    await page.getByLabel('Gym name').fill('Offline Gym')
    await page.getByRole('button', { name: 'Save gym' }).click()
    await expect(page.getByRole('button', { name: 'Edit Offline Gym', exact: true })).toBeFocused()
    await context.setOffline(true)
    await page.reload()
    await expect(page.locator('html')).toHaveAttribute('data-offline-ready', 'true')

    async function tabTo(target: Locator) {
      await expect(target).toBeVisible()
      for (let i = 0; i < 100; i++) {
        if (await target.evaluate(node => node === document.activeElement)) {
          await expect(target).toBeFocused()
          return
        }
        await page.keyboard.press('Tab')
      }
      throw new Error(`Keyboard could not reach ${await target.getAttribute('aria-label') ?? await target.textContent()}`)
    }
    async function enter(name: string) {
      await tabTo(page.getByRole('button', { name, exact: true }))
      await page.keyboard.press('Enter')
    }
    async function type(target: Locator, value: string) {
      await tabTo(target)
      await page.keyboard.press('ControlOrMeta+A')
      await page.keyboard.type(value)
    }
    async function section(name: string) {
      await tabTo(page.getByRole('tab', { selected: true }))
      await page.keyboard.press('Home')
      const names = ['Home', 'Train', 'Plan', 'History', 'Settings']
      for (let i = 0; i < names.indexOf(name); i++) await page.keyboard.press(viewport.width >= 768 ? 'ArrowDown' : 'ArrowRight')
      await expect(page.getByRole('tab', { name, exact: true })).toBeFocused()
      await expect(page.getByRole('tab', { name, exact: true })).toHaveAttribute('aria-selected', 'true')
    }

    await section('Train')
    await enter('Add exercise')
    await expect(page.getByLabel('Exercise name')).toBeFocused()
    await page.keyboard.type('Offline Row')
    await type(page.getByRole('textbox', { name: 'Notes', exact: true }), 'Original reference')
    await enter('Save exercise')
    await expect(page.getByRole('button', { name: 'Edit Offline Row', exact: true })).toBeFocused()
    await type(page.getByRole('searchbox', { name: 'Search exercises' }), 'Offline')
    await enter('Edit Offline Row')
    await type(page.getByRole('textbox', { name: 'Notes', exact: true }), 'Retained offline reference')
    await enter('Save changes')
    await expect(page.getByRole('button', { name: 'Edit Offline Row', exact: true })).toBeFocused()
    await page.reload()
    await section('Train')
    await expect(page.getByRole('article', { name: 'Offline Row', exact: true })).toContainText('Retained offline reference')

    await section('Plan')
    await enter('Add workout')
    await expect(page.getByLabel('Workout name')).toBeFocused()
    await page.keyboard.type('Offline Strength')
    await tabTo(page.getByRole('combobox', { name: 'Gym', exact: true }))
    await expect(page.getByRole('combobox', { name: 'Gym', exact: true }).locator('option:checked')).toHaveText('Offline Gym')
    await enter('Add Offline Row')
    await type(page.getByRole('spinbutton', { name: 'Set 1 weight (kg) — Offline Row, exercise 1', exact: true }), '40')
    await enter('Add set — Offline Row, exercise 1')
    await enter('Save workout')
    await expect(page.getByRole('button', { name: 'Edit Offline Strength', exact: true })).toBeFocused()
    await page.keyboard.press('Enter')
    await type(page.getByLabel('Workout name'), 'Unsaved name')
    await enter('Cancel')
    await expect(page.getByRole('button', { name: 'Edit Offline Strength', exact: true })).toBeFocused()
    await page.reload()
    await section('Plan')
    await enter('Edit Offline Strength')
    await expect(page.getByLabel('Workout name')).toHaveValue('Offline Strength')
    await expect(page.getByRole('spinbutton', { name: 'Set 1 weight (kg) — Offline Row, exercise 1', exact: true })).toHaveValue('40')
    await enter('Save workout')
    await expect(page.getByRole('button', { name: 'Edit Offline Strength', exact: true })).toBeFocused()

    await section('Home')
    await enter('Start workout at Offline Gym')
    await enter('Start Offline Strength')
    await expect(page.getByRole('heading', { name: 'Offline Strength', exact: true })).toBeFocused()
    await type(page.getByLabel('Offline Row set 1 weight'), '42.5')
    await enter('Log Offline Row set 1')
    await expect(page.getByText('1 of 2 sets logged · 0 skipped')).toBeVisible()
    await expect(page.getByRole('status')).toContainText('Suggested rest:')
    await expect(page.getByRole('timer', { name: 'Rest timer' })).toBeVisible()
    await enter('Skip Offline Row set 2')
    await expect(page.getByText('1 of 2 sets logged · 1 skipped')).toBeVisible()
    await enter('Return to Offline Row set 2')
    await expect(page.getByText('1 of 2 sets logged · 0 skipped')).toBeVisible()
    await enter('Skip exercise Offline Row')
    await expect(page.getByRole('button', { name: 'Return to exercise Offline Row', exact: true })).toBeFocused()
    await expect(page.getByRole('status')).toHaveText('Incomplete exercise sets skipped')
    await page.keyboard.press('Enter')
    await expect(page.getByRole('button', { name: 'Skip exercise Offline Row', exact: true })).toBeFocused()
    await expect(page.getByRole('status')).toHaveText('Incomplete exercise sets returned')
    await enter('Exit workout')
    await expect(page.getByRole('button', { name: 'Resume Offline Strength', exact: true })).toBeFocused()
    await page.reload()
    await expect(page.locator('html')).toHaveAttribute('data-offline-ready', 'true')
    await enter('Resume Offline Strength')
    await expect(page.getByRole('heading', { name: 'Offline Strength', exact: true })).toBeFocused()
    await expect(page.getByLabel('Offline Row set 1 weight')).toHaveValue('42.5')
    await expect(page.getByLabel('Offline Row set 1 weight')).toBeDisabled()
    await enter('Stop rest')
    await expect(page.getByRole('button', { name: 'Finish workout', exact: true })).toBeFocused()
    await expect(page.getByRole('status')).toHaveText('Rest stopped')
    await expect(page.getByRole('timer')).toHaveCount(0)
    await page.keyboard.press('Enter')
    await expect(page.getByRole('button', { name: 'Keep training', exact: true })).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(page.getByRole('button', { name: 'Finish workout', exact: true })).toBeFocused()
    await page.keyboard.press('Enter')
    await enter('Finish and skip 1 set')
    await expect(page.getByRole('heading', { name: 'Workout saved', exact: true })).toBeVisible()
    await enter('Back to home')
    await section('History')
    await enter('View details')
    const history = page.getByRole('article', { name: 'Offline Strength at Offline Gym', exact: true })
    await expect(history).toContainText('42.5 kg')
    await expect(history).toContainText('Skipped')
    await page.screenshot({ path: test.info().outputPath('offline-keyboard-history.png'), fullPage: true })
    await page.reload()
    await section('History')
    await expect(history).toBeVisible()
    await section('Settings')
    const downloading = page.waitForEvent('download')
    await enter('Download backup')
    await expect(page.getByRole('status').filter({ hasText: 'Backup downloaded.' })).toBeVisible()
    const backup: SpottrBackup = JSON.parse(await readFile((await (await downloading).path())!, 'utf8'))
    expect(backup.version).toBe(1)
    expect(backup.entities.gyms[0].name).toBe('Offline Gym')
    expect(backup.entities.exercises[0].notes).toBe('Retained offline reference')
    expect(backup.entities.workouts[0].exercises[0].sets[0].weight).toBe(40)
    expect(backup.entities.completedSessions).toHaveLength(1)
    expect(backup.entities.completedSessions[0].exercises[0].sets[0].weight).toBe(42.5)
    expect(backup.entities.completedSessions[0].exercises[0].sets[0].completedAt).not.toBeNull()
    expect(backup.entities.completedSessions[0].exercises[0].sets[1].skippedAt).not.toBeNull()
    expect(backup.entities.activeSession).toBeNull()
    expect(backup.settings).toBeDefined()
    await expect(page.locator('html')).toHaveAttribute('data-offline-ready', 'true')
  })
}
