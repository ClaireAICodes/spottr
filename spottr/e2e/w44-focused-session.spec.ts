import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { resolve } from 'node:path'

for (const width of [320, 390, 834]) {
  test(`focused 5x4 owned-reference journey at ${width}`, async ({ page }) => {
    await page.setViewportSize({ width, height: 844 })
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('/spottr/')
    await page.getByRole('tab', { name: 'Gyms', exact: true }).click()
    await page.getByRole('button', { name: 'Add gym', exact: true }).click()
    await page.getByLabel('Gym name').fill('Focus Gym')
    await page.getByRole('button', { name: 'Save gym', exact: true }).click()
    await page.getByRole('button', { name: 'Back to home' }).click()
    await page.getByRole('tab', { name: 'Exercises', exact: true }).click()
    const name = 'Long repeated controlled cable row'
    for (let i = 0; i < 5; i++) {
      await page.getByRole('button', { name: 'Add exercise', exact: true }).click()
      await page.getByLabel('Exercise name').fill(name)
      await page.getByLabel('Notes', { exact: true }).fill(`Owner-marker-${i}. Brace torso. Seat position 3.`)
      await page.getByRole('button', { name: 'Save exercise', exact: true }).click()
      await expect(page.getByRole('button', { name: 'Save exercise', exact: true })).toHaveCount(0)
      await expect(page.getByRole('article')).toHaveCount(i + 1)
      if (i === 0) {
        const owner = page.getByRole('article').filter({ hasText: 'Owner-marker-0.' })
        const picker = owner.getByLabel(`Add image or video — ${name}`, { exact: true })
        await picker.setInputFiles({ name: 'owned-setup.png', mimeType: 'image/png', buffer: await readFile(resolve('e2e/fixtures/owned-setup.png')) })
        await expect(owner.getByText('owned-setup.png', { exact: true })).toBeVisible()
        await expect(picker).toBeEnabled()
      }
    }
    await page.getByRole('tab', { name: 'Workouts', exact: true }).click()
    await page.getByRole('button', { name: 'Add workout', exact: true }).click()
    await page.getByLabel('Workout name').fill('Twenty sets')
    for (let i = 0; i < 5; i++) {
      await page.getByLabel('Search shared exercises').fill(`Owner-marker-${i}.`)
      await expect(page.getByRole('button', { name: `Add ${name}`, exact: true })).toHaveCount(1)
      await page.getByRole('button', { name: `Add ${name}`, exact: true }).click()
      const sets = page.getByRole('article', { name: `${name} sets`, exact: true }).nth(i)
      for (let j = 0; j < 3; j++) await sets.getByRole('button', { name: /^Add set/ }).click()
    }
    await page.getByRole('button', { name: 'Save workout', exact: true }).click()
    await page.getByRole('tab', { name: 'Home', exact: true }).click()
    await page.getByRole('button', { name: 'Start workout at Focus Gym' }).click()
    await page.getByRole('button', { name: 'Start Twenty sets', exact: true }).click()
    const stage = page.getByRole('region', { name: 'Current set', exact: true })
    await expect(stage.getByText('Set 1 of 4')).toBeVisible()
    await expect(page.getByRole('spinbutton')).toHaveCount(2)
    await expect(stage.getByText('Owner-marker-0. Brace torso. Seat position 3.')).toBeVisible()
    await stage.getByRole('button', { name: `Show reference media for ${name}` }).click()
    const image = stage.getByRole('img', { name: `${name}: owned-setup.png` })
    await expect.poll(() => image.evaluate((el: HTMLImageElement) => el.naturalWidth)).toBe(160)
    await page.screenshot({ path: `evidence/run562/reference-${width}.png`, fullPage: true })
    for (const control of await page.locator('.session-exercise-heading button').all()) {
      await control.scrollIntoViewIfNeeded()
      const box = await control.boundingBox()
      console.log(JSON.stringify({ phase: 'heading', width, box }))
      expect(box!.x + box!.width).toBeLessThanOrEqual(width)
      expect(box!.height).toBeGreaterThanOrEqual(52)
    }
    for (const label of ['Workout overview', 'Return to current set']) {
      const action = page.getByRole('button', { name: label, exact: true })
      await action.scrollIntoViewIfNeeded()
      const bounds = await action.evaluate(el => {
        const r = el.getBoundingClientRect()
        const hit = document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)
        return { width: r.width, height: r.height, left: r.left, right: r.right, top: r.top, bottom: r.bottom, hit: hit === el || el.contains(hit) }
      })
      console.log(JSON.stringify({ phase: 'overview-action', viewport: width, label, ...bounds }))
      expect(bounds.width).toBeGreaterThanOrEqual(44)
      expect(bounds.height).toBeGreaterThanOrEqual(52)
      expect(bounds.left).toBeGreaterThanOrEqual(0)
      expect(bounds.right).toBeLessThanOrEqual(width)
      expect(bounds.top).toBeGreaterThanOrEqual(0)
      expect(bounds.bottom).toBeLessThanOrEqual(844)
      expect(bounds.hit).toBe(true)
      await page.screenshot({ path: `evidence/run564/${label === 'Workout overview' ? 'focused' : 'overview'}-${width}.png`, fullPage: true })
      if (label === 'Workout overview') await action.click()
    }
    await expect(page.getByRole('spinbutton')).toHaveCount(40)
    await page.getByRole('button', { name: `Skip ${name} exercise 3 set 2`, exact: true }).click()
    await page.getByRole('button', { name: `Return to ${name} exercise 3 set 2`, exact: true }).click()
    await page.getByRole('button', { name: `Move ${name} down`, exact: true }).nth(2).click()
    const moved = page.getByRole('region', { name: 'Workout overview', exact: true }).locator('.session-exercise').nth(3)
    await expect(moved).toContainText('Owner-marker-2. Brace torso. Seat position 3.')
    await moved.getByRole('button', { name: `Select current ${name} exercise 4 set 2`, exact: true }).click()
    await expect(page.getByRole('spinbutton')).toHaveCount(2)
    await expect(page.getByText('0 of 20 sets logged · 0 skipped')).toBeVisible()
    await expect(stage.getByText('Set 2 of 4')).toBeVisible()
    for (const control of await page.locator('.session-exercise-heading button, [aria-label="Current set"] input, [aria-label="Current set"] button').all()) {
      await control.scrollIntoViewIfNeeded()
      const box = await control.boundingBox()
      expect(box!.width).toBeGreaterThanOrEqual(44)
      expect(box!.height).toBeGreaterThanOrEqual(52)
      expect(box!.x).toBeGreaterThanOrEqual(0)
      expect(box!.x + box!.width).toBeLessThanOrEqual(width)
      expect(await control.evaluate(el => {
        const r = el.getBoundingClientRect()
        const hit = document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)
        return hit === el || el.contains(hit)
      })).toBe(true)
    }
    console.log(JSON.stringify({ width, stageControls: await stage.locator('input, button').evaluateAll(els => els.map(el => ({ text: el.textContent, width: el.getBoundingClientRect().width, height: el.getBoundingClientRect().height }))) }))
    await page.screenshot({ path: `evidence/run562/selected-${width}.png`, fullPage: true })
    await expect(stage.getByText('Owner-marker-2. Brace torso. Seat position 3.')).toBeVisible()
    await stage.getByRole('button', { name: `Start ${name} exercise 4 set 2`, exact: true }).click()
    await stage.getByRole('button', { name: `Complete ${name} exercise 4 set 2`, exact: true }).click()
    await expect(page.getByRole('dialog', { name: `Confirm ${name} set 2` })).toBeVisible()
    await page.reload()
    await page.getByRole('button', { name: 'Resume Twenty sets', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: `Confirm ${name} set 2` })
    await dialog.getByLabel('Actual reps').fill('0')
    await dialog.getByRole('button', { name: 'Log set', exact: true }).click()
    await expect(dialog.getByRole('alert')).toBeVisible()
    await dialog.getByLabel('Actual reps').fill('7')
    await dialog.getByRole('button', { name: 'Retry log set', exact: true }).click()
    await expect(page.getByRole('timer', { name: 'Rest timer' })).toBeVisible()
    await page.screenshot({ path: `evidence/run562/rest-${width}.png`, fullPage: true })
    await page.getByRole('button', { name: 'Stop rest', exact: true }).click()
    await expect(page.getByRole('timer', { name: 'Rest timer' })).toHaveCount(0)
    await page.getByRole('button', { name: 'Finish workout', exact: true }).click()
    await page.getByRole('button', { name: 'Finish and skip 19 sets', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Workout saved' })).toBeVisible()
    await page.getByRole('button', { name: 'View history', exact: true }).click()
    const history = page.getByRole('article', { name: 'Twenty sets at Focus Gym', exact: true })
    await expect(history.getByRole('button', { name: /^Hide details for Twenty sets at Focus Gym completed/ })).toHaveAttribute('aria-expanded', 'true')
    await expect(history).toContainText('7 reps')
    await page.screenshot({ path: `evidence/run562/history-${width}.png`, fullPage: true })
    expect(errors).toEqual([])
  })
}
