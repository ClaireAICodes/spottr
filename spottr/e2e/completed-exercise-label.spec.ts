import { expect, test } from '@playwright/test'

test('exercise availability name agrees with its visible action before skipping, after return and when completed', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 667 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Manage gyms' }).click()
  await page.getByRole('button', { name: 'Add gym', exact: true }).click()
  await page.getByLabel('Gym name').fill('Label Gym')
  await page.getByRole('button', { name: 'Save gym' }).click()
  await page.getByRole('button', { name: 'Back to Home' }).click()
  await page.getByRole('tab', { name: 'Train' }).click()
  await page.getByRole('button', { name: 'Add exercise', exact: true }).click()
  await page.getByLabel('Exercise name').fill('Row')
  await page.getByRole('button', { name: 'Save exercise' }).click()
  await page.getByRole('tab', { name: 'Plan' }).click()
  await page.getByRole('button', { name: 'Add workout' }).click()
  await page.getByLabel('Workout name').fill('Label Workout')
  await page.getByRole('button', { name: 'Add Row' }).click()
  await page.getByRole('button', { name: 'Save workout' }).click()
  await page.getByRole('tab', { name: 'Home' }).click()
  await page.getByRole('button', { name: 'Start workout at Label Gym' }).click()
  await page.getByRole('button', { name: 'Start Label Workout' }).click()
  const skip = page.getByRole('button', { name: 'Skip exercise Row', exact: true })
  await expect(skip).toHaveText('Skip exercise for now')
  await skip.focus()
  await page.keyboard.press('Enter')
  const returnExercise = page.getByRole('button', { name: 'Return to exercise Row', exact: true })
  await expect(returnExercise).toHaveText('Return to exercise')
  await expect(returnExercise).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(skip).toBeFocused()
  await page.getByLabel('Row set 1 weight').fill('73')
  await page.getByRole('button', { name: 'Log Row set 1', exact: true }).click()
  await expect(page.getByText('1 of 1 sets logged · 0 skipped')).toBeVisible()
  await expect(skip).toHaveText('Skip exercise for now')
  await expect(skip).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Return to exercise Row', exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Row set 1 weight')).toHaveValue('73')
  await page.screenshot({ path: 'evidence/screenshots/completed-exercise-label-390.png', fullPage: true })
  await page.getByRole('button', { name: 'Exit workout' }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Resume Label Workout' }).click()
  await expect(skip).toBeDisabled()
  await expect(skip).toHaveText('Skip exercise for now')
  await expect(page.getByLabel('Row set 1 weight')).toHaveValue('73')
})
