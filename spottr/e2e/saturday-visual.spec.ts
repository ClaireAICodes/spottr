import { test, expect } from '@playwright/test'

// Approved seams: public UI, normal saved records, layout/hit geometry and motion.
for (const width of [320, 390, 834, 1440]) {
  test(`matched visual journey ${width}`, async ({ page }) => {
    await page.setViewportSize({ width, height: 844 })
    const errors: string[] = []
    page.on('pageerror', e => errors.push(e.message))
    const phase = process.env.VISUAL_PHASE || 'before'
    const capture = async (state: string) => {
      await page.evaluate(async () => { await Promise.all(document.getAnimations().map(a => a.finished.catch(() => {}))) })
      await page.screenshot({ path: `evidence/saturday/${phase}/${width}-${state}.png`, fullPage: true, animations: 'disabled' })
    }
    await page.goto('/spottr/')
    await expect(page.getByRole('tab', { name: 'Home', exact: true })).toBeVisible()
    await capture('welcome')
    await page.getByRole('tab', { name: 'Exercises', exact: true }).click()
    await capture('empty')
    await page.getByRole('button', { name: 'Add exercise', exact: true }).click()
    await page.getByLabel('Exercise name').fill('Controlled cable row — steady training')
    await page.getByLabel('Notes', { exact: true }).fill('Owned visual fixture. Brace torso and pause at the top.')
    await capture('editor')
    await page.getByRole('button', { name: 'Save exercise', exact: true }).click()
    await expect(page.getByRole('article')).toHaveCount(1)
    await capture('library')
    await page.getByRole('tab', { name: 'Gyms', exact: true }).click()
    await page.getByRole('button', { name: 'Add gym', exact: true }).click()
    await page.getByLabel('Gym name').fill('Saturday local gym')
    await page.getByRole('button', { name: 'Save gym', exact: true }).click()
    await page.getByRole('button', { name: 'Back to home' }).click()
    await page.getByRole('tab', { name: 'Workouts', exact: true }).click()
    await page.getByRole('button', { name: 'Add workout', exact: true }).click()
    await page.getByLabel('Workout name').fill('Steady strength')
    await page.getByRole('button', { name: 'Add Controlled cable row — steady training', exact: true }).click()
    await capture('planner')
    await page.getByRole('button', { name: 'Save workout', exact: true }).click()
    await page.getByRole('tab', { name: 'Home', exact: true }).click()
    await capture('populated')
    await page.getByRole('button', { name: 'Start workout at Saturday local gym' }).click()
    await capture('start')
    await page.getByRole('button', { name: 'Start Steady strength', exact: true }).click()
    const stage = page.getByRole('region', { name: 'Current set', exact: true })
    await expect(stage.getByText('Owned visual fixture. Brace torso and pause at the top.', { exact: true })).toBeVisible()
    await expect(page.locator('.session-exercise')).toHaveCSS('opacity', '1')
    await capture('stage')
    await stage.getByRole('button', { name: /^Start Controlled/ }).click()
    await stage.getByRole('button', { name: /^Complete Controlled/ }).click()
    const dialog = page.getByRole('dialog')
    await capture('confirmation')
    await dialog.getByLabel('Actual reps').fill('0')
    await dialog.getByRole('button', { name: 'Log set', exact: true }).click()
    await expect(dialog.getByRole('alert')).toBeVisible()
    await capture('error')
    for (const input of await dialog.locator('input').all()) {
      await input.focus()
      await input.scrollIntoViewIfNeeded()
      const geometry = await input.evaluate(el => {
        const r = el.getBoundingClientRect()
        const hit = document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)
        return { width: r.width, height: r.height, right: r.right, font: getComputedStyle(el).fontSize, hit: hit === el, scale: visualViewport?.scale }
      })
      console.log(JSON.stringify({ phase, width, geometry }))
      expect(geometry.width).toBeGreaterThanOrEqual(44)
      expect(geometry.height).toBeGreaterThanOrEqual(44)
      expect(geometry.right).toBeLessThanOrEqual(width)
      expect(geometry.hit).toBe(true)
      expect(parseFloat(geometry.font)).toBeGreaterThanOrEqual(16)
    }
    await dialog.getByLabel('Actual reps').fill('7')
    await dialog.getByRole('button', { name: 'Retry log set', exact: true }).click()
    await expect(page.getByRole('timer', { name: 'Rest timer' })).toBeVisible()
    await capture('rest')
    await page.getByRole('button', { name: 'Stop rest', exact: true }).click()
    await page.getByRole('button', { name: 'Finish workout', exact: true }).click()
    // The single completed set leaves no remaining-set confirmation.
    await expect(page.getByRole('heading', { name: 'Workout saved' })).toBeVisible()
    await capture('summary')
    await page.getByRole('button', { name: 'View history', exact: true }).click()
    await expect(page.getByRole('article')).toContainText('7 reps')
    await capture('history')
    await page.getByRole('tab', { name: 'Settings', exact: true }).click()
    await capture('settings')
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.getByRole('tab', { name: 'Home', exact: true }).click()
    await capture('reduced-motion')
    expect(errors).toEqual([])
  })
}
