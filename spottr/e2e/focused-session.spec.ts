import { expect, test } from '@playwright/test'

test('focused workout exits by keyboard and resumes saved progress with unobscured Finish at 390px', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Manage gyms' }).click()
  await page.getByRole('button', { name: 'Add gym', exact: true }).click()
  await page.getByLabel('Gym name').fill('Focus Gym')
  await page.getByRole('button', { name: 'Save gym' }).click()
  await page.getByRole('button', { name: 'Back to home' }).click()
  await page.getByRole('tab', { name: 'Train' }).click()
  for (const name of ['Row', 'Press']) {
    await page.getByRole('button', { name: 'Add exercise', exact: true }).click()
    await page.getByLabel('Exercise name').fill(name)
    await page.getByRole('button', { name: 'Save exercise' }).click()
  }
  await page.getByRole('tab', { name: 'Plan' }).click()
  await page.getByRole('button', { name: 'Add workout' }).click()
  await page.getByLabel('Workout name').fill('Focused Strength')
  await page.getByRole('button', { name: 'Add Row', exact: true }).click()
  await page.getByRole('button', { name: 'Add Press', exact: true }).click()
  await page.getByRole('button', { name: 'Save workout' }).click()
  await page.getByRole('tab', { name: 'Home' }).click()
  await page.getByRole('button', { name: 'Start workout at Focus Gym' }).click()
  await page.getByRole('button', { name: 'Start Focused Strength' }).click()
  await expect(page.getByRole('navigation', { name: 'Primary' })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Focused Strength', exact: true })).toBeFocused()
  await expect(page.getByRole('button', { name: 'Open profile' })).toHaveCount(0)
  await page.getByLabel('Row set 1 weight').fill('73')
  await page.getByRole('button', { name: 'Log Row set 1', exact: true }).click()
  await page.getByRole('button', { name: 'Skip exercise Press', exact: true }).click()
  await expect(page.getByText('1 of 2 sets logged · 1 skipped')).toBeVisible()
  await page.getByRole('button', { name: 'Exit workout', exact: true }).focus()
  await page.keyboard.press('Enter')
  const resume = page.getByRole('button', { name: 'Resume Focused Strength', exact: true })
  await expect(resume).toBeFocused()
  await expect(page.getByRole('navigation', { name: 'Primary' })).toBeVisible()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Focused Strength', exact: true })).toBeFocused()
  await expect(page.getByLabel('Row set 1 weight')).toHaveValue('73')
  await expect(page.getByRole('button', { name: 'Return to exercise Press', exact: true })).toBeEnabled()
  await expect(page.getByRole('timer', { name: 'Rest timer' })).toBeVisible()
  await page.reload()
  await resume.click()
  await expect(page.getByText('1 of 2 sets logged · 1 skipped')).toBeVisible()
  await expect(page.getByLabel('Row set 1 weight')).toHaveValue('73')
  await expect(page.getByRole('timer', { name: 'Rest timer' })).toBeVisible()
  const finish = page.getByRole('button', { name: 'Finish workout', exact: true })
  const measurements = []
  for (const state of ['keyboard-focus', 'minimal-scroll']) {
    if (state === 'keyboard-focus') await finish.focus()
    else await finish.scrollIntoViewIfNeeded()
    const bounds = await finish.evaluate((button) => {
      const r = button.getBoundingClientRect()
      // Edge midpoints stay inside the visible rounded button, unlike cut-out corners.
      const points = [[r.left + r.width / 2, r.top + r.height / 2], [r.left + 2, r.top + r.height / 2], [r.right - 2, r.top + r.height / 2], [r.left + r.width / 2, r.top + 2], [r.left + r.width / 2, r.bottom - 2]]
      return { width: r.width, height: r.height, left: r.left, right: r.right, top: r.top, bottom: r.bottom, viewportWidth: innerWidth, viewportHeight: innerHeight, hits: points.map(([x, y]) => button.contains(document.elementFromPoint(x, y))) }
    })
    expect(bounds.width).toBeGreaterThanOrEqual(44)
    expect(bounds.height).toBeGreaterThanOrEqual(44)
    expect(bounds.left).toBeGreaterThanOrEqual(0)
    expect(bounds.right).toBeLessThanOrEqual(bounds.viewportWidth)
    expect(bounds.top).toBeGreaterThanOrEqual(0)
    expect(bounds.bottom).toBeLessThanOrEqual(bounds.viewportHeight)
    expect(bounds.hits).toEqual([true, true, true, true, true])
    measurements.push({ state, ...bounds })
  }
  console.log('Finish target measurements', JSON.stringify(measurements))
  await page.screenshot({ path: 'evidence/screenshots/focused-finish-390.png' })
  await page.keyboard.press('Enter')
  await expect(page.getByRole('button', { name: 'Keep training' })).toBeFocused()
  await expect(page.getByRole('button', { name: 'Exit workout', exact: true })).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(finish).toBeFocused()
  await page.getByRole('button', { name: 'Return to exercise Press', exact: true }).click()
  await page.getByRole('button', { name: 'Log Press set 1', exact: true }).click()
  await finish.click()
  await expect(page.getByRole('heading', { name: 'Workout saved' })).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Primary' })).toBeVisible()
})
