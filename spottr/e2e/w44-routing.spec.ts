import { test, expect } from '@playwright/test'

test('preferred tabs, direct hashes and browser back retain gym data', async ({ page }) => {
  await page.goto('/spottr/#/gyms')
  await expect(page.getByRole('tab').allTextContents()).resolves.toEqual(['Home', 'Exercises', 'Workouts', 'Gyms', 'Settings'])
  await expect(page.getByRole('tab', { name: 'Gyms', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('button', { name: 'Add gym', exact: true }).click()
  await page.getByLabel('Gym name').fill('Routing preservation gym')
  await page.getByRole('button', { name: 'Save gym', exact: true }).click()
  await expect(page.getByRole('article', { name: 'Routing preservation gym' })).toBeVisible()
  await page.getByRole('tab', { name: 'Workouts', exact: true }).click()
  await page.getByRole('button', { name: 'History', exact: true }).click()
  await expect(page).toHaveURL(/#\/history$/)
  await page.getByRole('button', { name: 'Back to workouts', exact: true }).click()
  await expect(page).toHaveURL(/#\/workouts$/)
  await page.goBack()
  await expect(page.getByRole('heading', { name: 'Workout history', exact: true })).toBeVisible()
  await page.goto('/spottr/#/gyms')
  await expect(page.getByRole('article', { name: 'Routing preservation gym' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('article', { name: 'Routing preservation gym' })).toBeVisible()
  await page.goto('/spottr/#history')
  await expect(page).toHaveURL(/#\/history$/)
  await expect(page.getByRole('button', { name: 'Back to workouts' })).toBeVisible()
})
