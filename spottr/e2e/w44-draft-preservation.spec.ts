import { test, expect } from '@playwright/test'

test('opening History must not discard an unfinished workout', async ({ page }) => {
  await page.goto('/spottr/#/gyms')
  await page.getByRole('button', { name: 'Add gym', exact: true }).click()
  await page.getByLabel('Gym name').fill('Draft safety gym')
  await page.getByRole('button', { name: 'Save gym', exact: true }).click()
  await expect(page.getByRole('article', { name: 'Draft safety gym' })).toBeVisible()
  await page.getByRole('tab', { name: 'Workouts', exact: true }).click()
  await page.getByRole('button', { name: 'Add workout', exact: true }).click()
  await page.getByLabel('Workout name', { exact: true }).fill('Keep my unfinished routine')
  await page.getByRole('button', { name: 'History', exact: true }).click()
  await page.getByRole('button', { name: 'Back to workouts', exact: true }).click()
  await expect(page.getByLabel('Workout name', { exact: true })).toHaveValue('Keep my unfinished routine')
})

for (const width of [390, 320]) {
  test(`saved workout discard confirmation protects edits and reload recovery at ${width}`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 667 })
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('/spottr/#/gyms')
    await page.getByRole('button', { name: 'Add gym', exact: true }).click()
    await page.getByLabel('Gym name').fill('Discard gym')
    await page.getByRole('button', { name: 'Save gym', exact: true }).click()
    await expect(page.getByRole('article', { name: 'Discard gym' })).toBeVisible()
    await page.getByRole('tab', { name: 'Exercises', exact: true }).click()
    for (const name of ['Row', 'Squat']) {
      await page.getByRole('button', { name: 'Add exercise', exact: true }).click()
      await page.getByLabel('Exercise name', { exact: true }).fill(name)
      await page.getByRole('button', { name: 'Save exercise', exact: true }).click()
      await expect(page.getByRole('article', { name, exact: true })).toBeVisible()
    }
    await page.getByRole('tab', { name: 'Workouts', exact: true }).click()
    await page.getByRole('button', { name: 'Add workout', exact: true }).click()
    await page.getByLabel('Workout name', { exact: true }).fill('Original routine')
    for (const name of ['Row', 'Squat']) await page.getByRole('button', { name: `Add ${name}`, exact: true }).click()
    await page.getByLabel('Set 1 weight (kg) — Row, exercise 1', { exact: true }).fill('42')
    await page.getByRole('button', { name: 'Save workout', exact: true }).click()
    await page.getByRole('button', { name: 'Edit Original routine', exact: true }).click()
    await page.getByLabel('Workout name', { exact: true }).fill('Uncommitted routine')
    await page.getByRole('button', { name: 'Move exercise down — Row, exercise 1', exact: true }).click()
    await page.getByLabel('Set 1 weight (kg) — Row, exercise 2', { exact: true }).fill('17.5')
    await page.getByLabel('Set 1 reps — Row, exercise 2', { exact: true }).fill('')
    const cancel = page.getByRole('button', { name: 'Cancel', exact: true })
    const assertEdits = async () => {
      await expect(page.getByLabel('Workout name', { exact: true })).toHaveValue('Uncommitted routine')
      await expect(page.getByLabel('Set 1 weight (kg) — Row, exercise 2', { exact: true })).toHaveValue('17.5')
      await expect(page.getByLabel('Set 1 reps — Row, exercise 2', { exact: true })).toHaveValue('')
    }
    await cancel.click()
    const dialog = page.getByRole('dialog', { name: 'Discard draft?' })
    await expect(dialog.getByRole('button', { name: 'Keep editing' })).toBeFocused()
    for (const label of ['Keep editing', 'Discard']) {
      const control = dialog.getByRole('button', { name: label, exact: true })
      const bounds = await control.evaluate(el => {
        const r = el.getBoundingClientRect()
        const hit = document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)
        return { left: r.left, right: r.right, width: r.width, height: r.height, top: r.top, bottom: r.bottom, hit: hit === el || el.contains(hit) }
      })
      console.log(JSON.stringify({ phase: 'discard-dialog', viewport: width, label, ...bounds }))
      expect(bounds.width).toBeGreaterThanOrEqual(44)
      expect(bounds.height).toBeGreaterThanOrEqual(44)
      expect(bounds.left).toBeGreaterThanOrEqual(0)
      expect(bounds.right).toBeLessThanOrEqual(width)
      expect(bounds.top).toBeGreaterThanOrEqual(0)
      expect(bounds.bottom).toBeLessThanOrEqual(667)
      expect(bounds.hit).toBe(true)
    }
    await page.screenshot({ path: testInfo.outputPath(`dialog-${width}.png`), fullPage: true })
    await dialog.getByRole('button', { name: 'Keep editing' }).click()
    await expect(cancel).toBeFocused()
    await assertEdits()
    await cancel.click()
    await page.keyboard.press('Escape')
    await expect(cancel).toBeFocused()
    await assertEdits()
    await page.getByRole('tab', { name: 'Exercises', exact: true }).click()
    await page.getByRole('tab', { name: 'Workouts', exact: true }).click()
    await assertEdits()
    await page.reload()
    await assertEdits()
    await cancel.click()
    await dialog.getByRole('button', { name: 'Discard', exact: true }).click()
    await expect(page.getByLabel('Workout name', { exact: true })).toHaveCount(0)
    await page.reload()
    await page.getByRole('button', { name: 'Edit Original routine', exact: true }).click()
    await expect(page.getByLabel('Workout name', { exact: true })).toHaveValue('Original routine')
    await expect(page.getByLabel('Set 1 weight (kg) — Row, exercise 1', { exact: true })).toHaveValue('42')
    await expect(page.getByLabel('Set 1 reps — Row, exercise 1', { exact: true })).toHaveValue('8')
    await expect(page.getByLabel('Set 1 weight (kg) — Squat, exercise 2', { exact: true })).toHaveValue('0')
    await page.screenshot({ path: testInfo.outputPath(`restored-${width}.png`), fullPage: true })
    expect(errors).toEqual([])
  })
}
