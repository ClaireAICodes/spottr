import { expect, test, type Locator, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import type { SpottrBackup } from '../src/backup'
import { DEFAULT_SETTINGS } from '../src/settings'

async function reach(page: Page, target: Locator) {
  await expect(target).toBeVisible()
  for (let i = 0; i < 100; i++) {
    if (await target.evaluate(node => node === document.activeElement)) return
    await page.keyboard.press('Tab')
  }
  await expect(target).toBeFocused()
}
async function enter(page: Page, target: Locator) { await reach(page, target); await page.keyboard.press('Enter') }
async function type(page: Page, target: Locator, value: string) {
  await reach(page, target)
  await page.keyboard.press('ControlOrMeta+A')
  await page.keyboard.type(value)
}
async function section(page: Page, name: string) {
  await reach(page, page.getByRole('tab', { selected: true }))
  await page.keyboard.press('Home')
  for (let i = 0; i < ['Home', 'Exercises', 'Workouts', 'History', 'Settings'].indexOf(name); i++) await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('tab', { name, exact: true })).toBeFocused()
}
async function exported(page: Page): Promise<SpottrBackup> {
  const downloading = page.waitForEvent('download')
  await enter(page, page.getByRole('button', { name: 'Download backup', exact: true }))
  await expect(page.getByRole('status').filter({ hasText: 'Backup downloaded.' })).toBeVisible()
  const download = await downloading
  await download.saveAs(test.info().outputPath(`backup-${test.info().attachments.length}.json`))
  const text = await readFile((await download.path())!, 'utf8')
  await test.info().attach('public-backup', { body: text, contentType: 'application/json' })
  return JSON.parse(text)
}

test('one cached-ready offline timed session preserves actuals, declined targets and history', async ({ page, context }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  // Injected, paused clock is emulation, not physical suspension evidence.
  await page.clock.install({ time: new Date('2026-10-13T08:00:00Z') })
  await page.clock.pauseAt(new Date('2026-10-13T08:00:01Z'))
  await page.goto('/spottr/')
  await expect(page.locator('html')).toHaveAttribute('data-offline-ready', 'true')
  await expect.poll(() => page.evaluate(() => navigator.serviceWorker.controller?.scriptURL)).toBe('http://127.0.0.1:4173/spottr/sw.js')
  await context.setOffline(true)
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-offline-ready', 'true')
  expect(await page.evaluate(() => navigator.onLine)).toBe(false)
  expect(await page.evaluate(async () => {
    const registration = await navigator.serviceWorker.getRegistration()
    return { url: location.href, controller: navigator.serviceWorker.controller?.scriptURL, scope: registration?.scope }
  })).toEqual({ url: 'http://127.0.0.1:4173/spottr/', controller: 'http://127.0.0.1:4173/spottr/sw.js', scope: 'http://127.0.0.1:4173/spottr/' })
  await test.info().attach('offline-receipt', { body: JSON.stringify({ origin: page.url(), offline: true, setup: 'all authoring via natural keyboard after offline reload', clock: 'Playwright paused clock' }), contentType: 'application/json' })

  const button = (name: string) => page.getByRole('button', { name, exact: true })
  await enter(page, button('Manage gyms'))
  await enter(page, button('Add gym'))
  await expect(page.getByLabel('Gym name')).toBeFocused()
  await page.keyboard.type('Integration Gym')
  await enter(page, button('Save gym'))
  await expect(button('Edit Integration Gym')).toBeFocused()
  await section(page, 'Workouts')
  await enter(page, button('Add workout'))
  await expect(page.getByLabel('Workout name')).toBeFocused()
  await page.keyboard.type('Offline Timed Row')
  await enter(page, button('Create new exercise'))
  await expect(page.getByLabel('Exercise name')).toBeFocused()
  await page.keyboard.type('Row')
  await enter(page, button('Save exercise'))
  await type(page, page.getByRole('spinbutton', { name: 'Set 1 weight (kg) — Row, exercise 1', exact: true }), '40')
  await type(page, page.getByRole('spinbutton', { name: 'Set 1 reps — Row, exercise 1', exact: true }), '8')
  await enter(page, button('Add set — Row, exercise 1'))
  await enter(page, button('Save workout'))
  await expect(button('Edit Offline Timed Row')).toBeFocused()
  await section(page, 'Home')
  await enter(page, button('Start workout at Integration Gym'))
  await enter(page, button('Start Offline Timed Row'))
  await expect(page.getByRole('heading', { name: 'Offline Timed Row', exact: true })).toBeFocused()
  const weight = page.getByLabel('Row set 1 weight (kg)', { exact: true })
  await type(page, weight, '42.5')
  await type(page, page.getByLabel('Row set 1 reps', { exact: true }), '9')
  const startedAt = await page.evaluate(() => new Date().toISOString())
  await enter(page, button('Start Row set 1'))
  await expect(button('Complete Row set 1')).toBeFocused()
  await expect(button('Log Row set 1')).toBeDisabled()
  await page.clock.fastForward(12000)
  await expect(page.getByRole('timer', { name: 'Elapsed Row set 1' })).toHaveText('0:12')
  await page.reload()
  await enter(page, button('Resume Offline Timed Row'))
  await expect(page.getByRole('heading', { name: 'Offline Timed Row', exact: true })).toBeFocused()
  await expect(weight).toHaveValue('42.5')
  await expect(page.getByLabel('Row set 1 reps', { exact: true })).toHaveValue('9')
  await expect(page.getByRole('timer', { name: 'Elapsed Row set 1' })).toHaveText('0:12')
  const endedAt = await page.evaluate(() => new Date().toISOString())
  await enter(page, button('Complete Row set 1'))
  await expect(weight).toBeFocused()
  await expect(page.getByText('Awaiting actuals', { exact: true })).toBeVisible()
  await type(page, weight, '43')
  await type(page, page.getByLabel('Row set 1 reps', { exact: true }), '7')
  await enter(page, button('Log Row set 1'))
  await expect(button('Stop rest')).toBeFocused()
  await expect(page.getByText('1 of 2 sets logged · 0 skipped')).toBeVisible()
  await page.clock.fastForward(17000)
  await expect(page.getByRole('timer', { name: 'Rest timer' })).toHaveText('0:17')
  await enter(page, button('Stop rest'))
  await expect(button('Finish workout')).toBeFocused()
  await expect(page.getByRole('status')).toHaveText('Rest stopped')
  await expect(page.getByRole('timer')).toHaveCount(0)
  await enter(page, button('Skip Row set 2'))
  await expect(page.getByText('1 of 2 sets logged · 1 skipped')).toBeVisible()
  await enter(page, button('Return to Row set 2'))
  await expect(page.getByText('1 of 2 sets logged · 0 skipped')).toBeVisible()
  // Export the same active public dataset to bind durable identities before Finish.
  await enter(page, button('Exit workout'))
  await expect(button('Resume Offline Timed Row')).toBeFocused()
  await section(page, 'Settings')
  const before = await exported(page)
  const active = before.entities.activeSession!
  expect(active).toMatchObject({ name: 'Offline Timed Row', gymName: 'Integration Gym' })
  expect(active.restTimer).toBeUndefined()
  expect(active.exercises[0].sets[0]).toMatchObject({ targetWeight: 40, targetReps: 8, weight: 43, reps: 7, timing: { startedAt, endedAt, durationSeconds: 12 }, completedAt: endedAt, skippedAt: null })
  expect(active.exercises[0].sets[1].timing).toBeUndefined()
  await section(page, 'Home')
  await enter(page, button('Resume Offline Timed Row'))
  await expect(page.getByRole('heading', { name: 'Offline Timed Row', exact: true })).toBeFocused()
  await enter(page, button('Finish workout'))
  await expect(button('Keep training')).toBeFocused()
  await enter(page, button('Finish and skip 1 set'))
  await expect(page.getByRole('heading', { name: 'Workout saved', exact: true })).toBeVisible()
  const decision = page.getByRole('group', { name: 'Future target for Row set 1' })
  await expect(decision).toContainText('Current target: 40 kg × 8 reps')
  await enter(page, decision.getByRole('button', { name: 'Keep current target', exact: true }))
  await expect(decision.getByRole('status')).toBeFocused()
  await expect(decision.getByRole('status')).toHaveText('Current target kept')
  await enter(page, button('View history'))
  const history = page.getByRole('article', { name: 'Offline Timed Row at Integration Gym', exact: true })
  await expect(history).toBeVisible()
  await enter(page, history.getByRole('button', { name: 'View details', exact: true }))
  await expect(history).toContainText('43 kg × 7 reps')
  await expect(history).toContainText('Skipped')
  await page.screenshot({ path: test.info().outputPath('offline-history.png'), fullPage: true })
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-offline-ready', 'true')
  expect(await page.evaluate(() => navigator.onLine)).toBe(false)
  await section(page, 'History')
  await expect(history).toBeVisible()
  await section(page, 'Settings')
  const after = await exported(page)
  expect(after.settings).toEqual(DEFAULT_SETTINGS)
  expect(after.entities.gyms).toEqual(before.entities.gyms)
  expect(after.entities.exercises).toEqual(before.entities.exercises)
  expect(after.entities.workouts).toEqual(before.entities.workouts)
  expect(after.entities.activeSession).toBeNull()
  expect(after.entities.completedSessions).toHaveLength(1)
  const completed = after.entities.completedSessions[0]
  expect(completed).toMatchObject({ id: active.id, templateId: before.entities.workouts[0].id, gymId: before.entities.gyms[0].id, name: active.name, gymName: active.gymName, startedAt: active.startedAt, summary: { completedSets: 1, skippedSets: 1, completedExercises: 1, skippedExercises: 0, volume: 301, durationSeconds: 29 } })
  expect(completed.exercises[0]).toMatchObject({ id: active.exercises[0].id, exerciseId: before.entities.exercises[0].id, templateExerciseId: before.entities.workouts[0].exercises[0].id })
  expect(completed.exercises[0].sets[0]).toEqual({ ...active.exercises[0].sets[0], targetDecision: 'declined' })
  expect(completed.exercises[0].sets[1]).toEqual({ ...active.exercises[0].sets[1], skippedAt: completed.endedAt })
  expect(completed.exercises[0].sets[1].timing).toBeUndefined()
  expect(before.entities.workouts[0].exercises[0].sets[0]).toMatchObject({ weight: 40, reps: 8 })
})
