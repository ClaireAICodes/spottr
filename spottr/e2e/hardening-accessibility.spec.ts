import { expect, test } from '@playwright/test'

test('empty-state gym editor returns keyboard focus to the live first-gym action on cancel', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Manage gyms' }).click()
  const add = page.getByRole('button', { name: 'Add your first gym', exact: true })
  await add.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Gym name')).toBeFocused()
  await page.getByRole('button', { name: 'Cancel', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(add).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Gym name')).toBeFocused()
})

test('gym editor has named actions and returns keyboard focus on cancel', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Manage gyms' }).click()
  const add = page.getByRole('button', { name: 'Add gym', exact: true })
  await add.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Gym name')).toBeFocused()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(add).toBeFocused()
  await add.click()
  await page.getByLabel('Gym name').fill('North Gym')
  await page.getByRole('button', { name: 'Save gym' }).click()
  const edit = page.getByRole('button', { name: 'Edit North Gym', exact: true })
  await edit.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Gym name')).toBeFocused()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(edit).toBeFocused()
})

test('workout editor and duplication restore focus to named invoking actions', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Manage gyms' }).click()
  await page.getByRole('button', { name: 'Add gym', exact: true }).click()
  await page.getByLabel('Gym name').fill('North Gym')
  await page.getByRole('button', { name: 'Save gym' }).click()
  await page.getByRole('tab', { name: 'Train', exact: true }).click()
  await page.getByRole('button', { name: 'Add exercise', exact: true }).click()
  await page.getByLabel('Exercise name').fill('Squat')
  await page.getByRole('button', { name: 'Save exercise' }).click()
  await page.getByRole('tab', { name: 'Plan', exact: true }).click()
  const add = page.getByRole('button', { name: 'Add workout', exact: true })
  await expect(add).toBeEnabled()
  await add.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Workout name')).toBeFocused()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(add).toBeFocused()
  await add.click()
  await page.getByLabel('Workout name').fill('Strength')
  await page.getByRole('button', { name: 'Add Squat', exact: true }).click()
  await page.getByRole('button', { name: 'Save workout' }).click()
  const edit = page.getByRole('button', { name: 'Edit Strength', exact: true })
  await edit.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Workout name')).toBeFocused()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(edit).toBeFocused()
  const duplicate = page.getByRole('button', { name: 'Duplicate Strength', exact: true })
  await duplicate.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Duplicate to gym')).toBeFocused()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(duplicate).toBeFocused()
  await expect(page.getByRole('button', { name: 'Delete Strength', exact: true })).toBeVisible()
  await page.screenshot({ path: 'evidence/screenshots/thursday-afternoon-focus.png', fullPage: true })
})
