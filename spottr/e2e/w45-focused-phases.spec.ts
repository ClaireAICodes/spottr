import { expect, test } from '@playwright/test'

for (const height of [667, 844]) test(`focused rest performing confirm offline resume ${height}`, async ({ page, context }) => {
  await page.setViewportSize({ width: 390, height })
  await page.goto('/')
  await page.getByRole('button', { name: 'Manage gyms' }).click()
  await page.getByRole('button', { name: 'Add gym', exact: true }).click()
  await page.getByLabel('Gym name').fill('Focus Gym')
  await page.getByRole('button', { name: 'Save gym', exact: true }).click()
  await page.getByRole('tab', { name: 'Workouts', exact: true }).click()
  await page.getByRole('button', { name: 'Add workout', exact: true }).click()
  await page.getByLabel('Workout name').fill('Focused twenty')
  for (let i = 1; i <= 5; i++) {
    await page.getByRole('button', { name: 'Create new exercise', exact: true }).click()
    await page.getByLabel('Exercise name').fill(`Controlled cable row ${i}`)
    await page.getByRole('button', { name: 'Save exercise', exact: true }).click()
    for (let j = 0; j < 3; j++) await page.getByRole('button', { name: `Add set — Controlled cable row ${i}, exercise ${i}`, exact: true }).click()
  }
  await page.getByRole('button', { name: 'Save workout', exact: true }).click()
  await page.getByRole('tab', { name: 'Home', exact: true }).click()
  await page.getByRole('button', { name: 'Start workout at Focus Gym' }).click()
  await page.getByRole('button', { name: 'Start Focused twenty', exact: true }).click()
  await expect(page.getByRole('spinbutton')).toHaveCount(0)
  await expect(page.getByRole('button', { name: /^Log / })).toHaveCount(0)
  await page.screenshot({ path: `evidence/w45/ready-${height}.png`, fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Start Controlled cable row 1 set 1', exact: true }).click()
  await expect(page.getByRole('spinbutton')).toHaveCount(0)
  await page.getByRole('button', { name: 'Complete Controlled cable row 1 set 1', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Confirm Controlled cable row 1 set 1' })
  await dialog.getByLabel('Actual weight (kg)').fill('40')
  await dialog.getByLabel('Actual reps', { exact: true }).fill('8')
  await dialog.getByRole('button', { name: 'Log set', exact: true }).click()
  await expect(page.getByRole('timer', { name: 'Rest timer' })).toBeVisible()
  await expect(page.getByRole('spinbutton')).toHaveCount(0)
  await expect(page.getByRole('button', { name: /^Log / })).toHaveCount(0)
  await page.screenshot({ path: `evidence/w45/rest-${height}.png`, fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Workout overview', exact: true }).click()
  await expect(page.getByRole('timer', { name: 'Rest timer' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Return to current set', exact: true })).toBeFocused()
  await page.screenshot({ path: `evidence/w45/overview-${height}.png`, fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Return to current set', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Workout overview', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Start next set', exact: true }).click()
  await expect(page.getByRole('timer', { name: 'Rest timer' })).toHaveCount(0)
  await expect(page.getByRole('spinbutton')).toHaveCount(0)
  await expect(page.getByRole('button', { name: /^Log / })).toHaveCount(0)
  await page.screenshot({ path: `evidence/w45/performing-${height}.png`, fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Workout overview', exact: true }).click()
  await expect(page.getByRole('spinbutton')).toHaveCount(0)
  await expect(page.getByRole('button', { name: /^Log / })).toHaveCount(0)
  await expect(page.getByRole('timer', { name: 'Rest timer' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Return to current set', exact: true }).click()
  await page.reload()
  await context.setOffline(true)
  await page.getByRole('button', { name: 'Resume Focused twenty', exact: true }).click()
  await page.getByRole('button', { name: 'Complete Controlled cable row 1 set 2', exact: true }).click()
  const second = page.getByRole('dialog', { name: 'Confirm Controlled cable row 1 set 2' })
  await expect(second).toBeVisible()
  await page.screenshot({ path: `evidence/w45/confirm-${height}.png`, fullPage: true, animations: 'disabled' })
  await second.getByLabel('Actual weight (kg)').fill('40')
  await second.getByLabel('Actual reps', { exact: true }).fill('8')
  await second.getByLabel('Actual reps', { exact: true }).fill('0')
  await second.getByRole('button', { name: 'Log set', exact: true }).click()
  await expect(second.getByRole('alert')).toBeVisible()
  await expect(page.getByRole('timer', { name: 'Rest timer' })).toHaveCount(0)
  await page.screenshot({ path: `evidence/w45/error-${height}.png`, fullPage: true, animations: 'disabled' })
  await second.getByLabel('Actual reps', { exact: true }).fill('8')
  await second.getByRole('button', { name: 'Retry log set', exact: true }).dblclick()
  await expect(page.getByRole('timer', { name: 'Rest timer' })).toHaveText('0:00')
  await expect(page.getByText('2 of 20 sets logged · 0 skipped · 18 remaining')).toBeVisible()
  await context.setOffline(false)
})
