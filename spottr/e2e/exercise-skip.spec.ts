import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('whole-exercise skip preserves logged actuals, survives backup/reload and returns incomplete work', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Manage gyms' }).click()
  await page.getByRole('button', { name: 'Add gym', exact: true }).click()
  await page.getByLabel('Gym name').fill('Skip Gym')
  await page.getByRole('button', { name: 'Save gym' }).click()
  await page.getByRole('button', { name: 'Back to home' }).click()
  await page.getByRole('tab', { name: 'Exercises' }).click()
  await page.getByRole('button', { name: 'Add exercise', exact: true }).click()
  await page.getByLabel('Exercise name').fill('Row')
  await page.getByRole('button', { name: 'Save exercise' }).click()
  await page.getByRole('tab', { name: 'Workouts' }).click()
  await page.getByRole('button', { name: 'Add workout' }).click()
  await page.getByLabel('Workout name').fill('Skip Recovery')
  await page.getByRole('button', { name: 'Add Row' }).click()
  await page.getByRole('button', { name: 'Add set' }).click()
  await page.getByRole('button', { name: 'Add set' }).click()
  await page.getByRole('button', { name: 'Save workout' }).click()
  await page.getByRole('tab', { name: 'Home' }).click()
  await page.getByRole('button', { name: 'Start workout at Skip Gym' }).click()
  await page.getByRole('button', { name: 'Start Skip Recovery' }).click()
  await page.getByLabel('Row set 1 weight').fill('50')
  await page.getByRole('button', { name: 'Log Row set 1' }).click()
  await expect(page.getByText('1 of 3 sets logged')).toBeVisible()
  await page.getByLabel('Row set 2 weight').fill('500')
  const skip = page.getByRole('button', { name: 'Skip exercise Row', exact: true })
  // Fail the actual storage boundary once; no service/repository result is fabricated.
  await page.evaluate(() => {
    const put = IDBObjectStore.prototype.put
    IDBObjectStore.prototype.put = function (...args: Parameters<IDBObjectStore['put']>) {
      IDBObjectStore.prototype.put = put
      throw new Error('Exercise save failed once')
    }
  })
  await skip.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('alert')).toHaveText('Exercise save failed once')
  await expect(page.getByText('1 of 3 sets logged · 0 skipped')).toBeVisible()
  await expect(page.getByLabel('Row set 2 weight')).toHaveValue('500')
  await expect(page.getByLabel('Row set 2 weight')).toBeEnabled()
  await expect(skip).toBeFocused()
  await skip.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByText('1 of 3 sets logged · 2 skipped')).toBeVisible()
  await expect(page.getByLabel('Row set 1 weight')).toHaveValue('50')
  await expect(page.getByLabel('Row set 2 weight')).toHaveValue('500')
  await expect(page.getByLabel('Row set 2 weight')).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Return to exercise Row', exact: true })).toBeFocused()
  await page.screenshot({ path: 'evidence/screenshots/exercise-skip-390.png' })
  await page.getByRole('button', { name: 'Exit workout' }).click()
  await page.getByRole('tab', { name: 'Settings' }).click()
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download backup' }).click()
  const backup = JSON.parse(await readFile((await (await downloading).path())!, 'utf8'))
  expect(backup.version).toBe(1)
  const sets = backup.entities.activeSession.exercises[0].sets
  expect(sets[0].weight).toBe(50)
  expect(sets[0].completedAt).not.toBeNull()
  expect(sets.slice(1).every((set: { skippedAt: string; personalRecords: string[] }) => set.skippedAt && set.personalRecords.length === 0)).toBe(true)
  await page.getByLabel('Choose backup file').setInputFiles({ name: 'skip.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) })
  await page.getByRole('button', { name: 'Restore backup' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Backup restored' })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Resume Skip Recovery' }).click()
  await expect(page.getByText('1 of 3 sets logged · 2 skipped')).toBeVisible()
  await page.getByRole('button', { name: 'Return to exercise Row', exact: true }).click()
  await expect(page.getByText('1 of 3 sets logged · 0 skipped')).toBeVisible()
  await expect(page.getByLabel('Row set 1 weight')).toHaveValue('50')
  await expect(page.getByLabel('Row set 1 weight')).toBeDisabled()
  await page.getByLabel('Row set 2 weight').fill('40')
  await page.getByRole('button', { name: 'Log Row set 2' }).click()
  await expect(page.getByText('2 of 3 sets logged')).toBeVisible()
  await expect(page.getByRole('status').filter({ hasText: 'New weight PR' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Skip exercise Row', exact: true }).click()
  await page.getByRole('button', { name: 'Exit workout' }).click()
  await page.getByRole('tab', { name: 'Workouts' }).click()
  await page.getByRole('article', { name: 'Skip Recovery' }).getByRole('button', { name: 'Edit' }).click()
  await expect(page.getByRole('article', { name: 'Row sets' }).getByLabel('Set 1 weight')).toHaveValue('0')
  await page.getByRole('tab', { name: 'Home' }).click()
  await page.getByRole('button', { name: 'Resume Skip Recovery' }).click()
  await page.getByRole('button', { name: 'Finish workout' }).click()
  await page.getByRole('button', { name: 'Finish and skip 1 set' }).click()
  await expect(page.getByRole('heading', { name: 'Workout saved' })).toBeVisible()
})
